import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'

// Run from any directory after intentionally updating the retained template.
const input = new URL('../../docs/Template_Penilaian_Satu_Siswa_SMA_JOINTS.docx', import.meta.url)
const bytes = readFileSync(input)
const sha = createHash('sha256').update(bytes).digest('hex')
const output = new URL('../src/reports/template.ts', import.meta.url)
writeFileSync(output, `// Generated by backend/scripts/embed-report-template.mjs. Do not edit by hand.\n// Source: docs/Template_Penilaian_Satu_Siswa_SMA_JOINTS.docx\n// Embedded so source bundling needs no external template file at runtime.\nexport const jointsTemplateSha256 = '${sha}'\nexport const jointsTemplateBase64 = '${bytes.toString('base64')}'\n`)
